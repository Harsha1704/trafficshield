"""
CICIDS2017 Unidirectional Feature Eligibility Policy
=====================================================
Milestone 10 — TrafficShield

Defines explicit, auditable directional classifications and availability timings
for 58 primary fields produced by the CICFlowMeter tool on the CICIDS2017 dataset,
supplemented by automated fail-safe keyword filtering for unmapped columns.

Background:
CICIDS2017 was generated by the Canadian Institute for Cybersecurity using
CICFlowMeter. Unlike unidirectional flow captures, CICFlowMeter generates extensive
bidirectional session aggregates and explicit backward/return metrics.

TrafficShield operates strictly on unidirectional links where return packets are
unobservable. Therefore, all backward metrics, bidirectional flags, response times,
and future session aggregates are strictly classified and PROHIBITED from entering
model feature matrices.
"""
from __future__ import annotations

from dataclasses import dataclass
from enum import StrEnum
from typing import Any

from features.policy import (
    DataType,
    FeatureAuditResult,
    FieldRole,
)


class CICIDSFeatureDirectionality(StrEnum):
    """Directionality classification of CICIDS2017 candidate fields."""
    FORWARD_OBSERVABLE = "forward_observable"
    REVERSE_DIRECTION = "reverse_direction"
    BIDIRECTIONAL_OR_FUTURE_DEPENDENT = "bidirectional_or_future_dependent"
    IDENTIFIER_OR_GROUPING_ONLY = "identifier_or_grouping_only"
    EVALUATION_LABEL = "evaluation_label"
    UNKNOWN = "unknown"


class AvailabilityTiming(StrEnum):
    """When a feature becomes observable during the flow life cycle."""
    PACKET_ARRIVAL = "packet_arrival"
    FLOW_PREFIX = "flow_prefix"
    FLOW_COMPLETION = "flow_completion"
    POST_EVENT = "post_event"


@dataclass(frozen=True)
class CICIDSFieldSpec:
    """Detailed contract for a CICIDS2017 dataset column."""
    index: int
    raw_name: str
    normalized_name: str
    directionality: CICIDSFeatureDirectionality
    field_role: FieldRole
    data_type: DataType
    availability_timing: AvailabilityTiming
    description: str
    rationale: str
    is_causal: bool = True
    causal_notes: str = ""

    @property
    def is_model_feature(self) -> bool:
        """True only if forward-observable and designated as a model feature."""
        return (
            self.directionality == CICIDSFeatureDirectionality.FORWARD_OBSERVABLE
            and self.field_role == FieldRole.FEATURE
        )

    def to_dict(self) -> dict[str, Any]:
        return {
            "index": self.index,
            "raw_name": self.raw_name,
            "normalized_name": self.normalized_name,
            "directionality": str(self.directionality),
            "field_role": str(self.field_role),
            "data_type": str(self.data_type),
            "availability_timing": str(self.availability_timing),
            "is_model_feature": self.is_model_feature,
            "is_causal": self.is_causal,
            "causal_notes": self.causal_notes,
            "description": self.description,
            "rationale": self.rationale,
        }


