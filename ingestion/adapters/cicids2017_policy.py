def audit_cicids2017_columns(columns: list[str]) -> FeatureAuditResult:
    """
    Audit an input column list from a CICIDS2017 file against unidirectional policy.

    Rejects:
    - Any reverse-direction column (e.g. 'Total Backward Packets', 'Bwd IAT Mean')
    - Any bidirectional aggregate (e.g. 'Flow Bytes/s', 'Packet Length Mean')
    - Target label ('Label')
    """
    clean_cols = [c.strip() for c in columns]
    forbidden_found: list[str] = []
    labels_found: list[str] = []
    identifiers_found: list[str] = []
    eligible_found: list[str] = []
    unknown_found: list[str] = []

    for raw_col in clean_cols:
        spec = CICIDS_2017_SPECS.get(raw_col)
        if spec is None:
            # Check for Bwd in name as an immediate fail-safe
            if "bwd" in raw_col.lower() or "backward" in raw_col.lower():
                forbidden_found.append(raw_col)
            elif "label" in raw_col.lower():
                labels_found.append(raw_col)
            else:
                unknown_found.append(raw_col)
            continue

        if spec.field_role == FieldRole.LABEL:
            labels_found.append(raw_col)
        elif spec.field_role == FieldRole.FORBIDDEN or spec.directionality in (
            CICIDSFeatureDirectionality.REVERSE_DIRECTION,
            CICIDSFeatureDirectionality.BIDIRECTIONAL_OR_FUTURE_DEPENDENT,
        ):
            forbidden_found.append(raw_col)
        elif spec.field_role == FieldRole.IDENTIFIER:
            identifiers_found.append(raw_col)
        elif spec.is_model_feature:
            eligible_found.append(raw_col)
        else:
            unknown_found.append(raw_col)

    excluded_dict: dict[str, str] = {}
    for c in identifiers_found:
        excluded_dict[c] = "identifier"
    for c in unknown_found:
        excluded_dict[c] = "unknown_or_metadata"

    return FeatureAuditResult(
        eligible_features=eligible_found,
        excluded_columns=excluded_dict,
        forbidden_violations=forbidden_found,
        label_violations=labels_found,
    )


def get_eligible_cicids_model_features() -> list[str]:
    """Return all forward-observable feature names designated for model input."""
    return [
        spec.raw_name
        for spec in CICIDS_2017_SPECS.values()
        if spec.is_model_feature
    ]
